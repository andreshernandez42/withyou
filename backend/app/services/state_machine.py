CASE_TRANSITIONS={
    'OPEN':{'VERIFICATION_IN_PROGRESS','INSTITUTIONAL_REFERENCE_ADDED','LOCATED_SAFE','LOCATED_HELP_REQUIRED','CLOSED'},
    'VERIFICATION_IN_PROGRESS':{'INSTITUTIONAL_REFERENCE_ADDED','LOCATED_SAFE','LOCATED_HELP_REQUIRED','CLOSED'},
    'INSTITUTIONAL_REFERENCE_ADDED':{'LOCATED_SAFE','LOCATED_HELP_REQUIRED','CLOSED'},
    'LOCATED_SAFE':{'CLOSED'},
    'LOCATED_HELP_REQUIRED':{'CLOSED'},
    'CLOSED':set(),
}

def can_transition_case(current:str,target:str)->bool:
    return target==current or target in CASE_TRANSITIONS.get(current,set())
